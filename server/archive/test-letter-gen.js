const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();
async function checkCurrent() {
            let organization = await prisma.organizationConfig.findUnique({
                where: { id: 'singleton' }
            });

            const roBranch = await prisma.branch.findFirst({
                where: { type: 'RO' }
            });

            const meta = {
                ...organization,
                officeNameEn: roBranch?.nameEn || "Dindigul Regional Office",
                officeNameTa: roBranch?.nameTa || "??????????? ????? ????????",
                officeNameHi: roBranch?.nameHi || "???????? ????????? ????????",
                address: roBranch?.address || "Regional Office, 123 Madurai Road, Dindigul - 624001, Tamil Nadu",
                addressTa: roBranch?.addressTa || "????? ????????, 123 ????? ????, ??????????? - 624001, ?????????",
                addressHi: roBranch?.addressHi || "????????? ????????, 123 ????? ???, ???????? - 624001, ????????"
            };
            console.log(JSON.stringify(meta, null, 2));
}
checkCurrent().catch(console.error).finally(() => prisma.$disconnect());
